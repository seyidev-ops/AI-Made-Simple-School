#!/usr/bin/env python3
"""
First-use access codes for AI Made Simple School.

A first-use code is valid for N days counted from the moment the learner first logs in
with it (not from the day you generate it or sell it).

What this script does
  1. Makes COUNT new random codes, e.g.  SPR-K7M2Q-9XD4P
  2. Adds ONLY their hashes to tools/codes/hashes.json (public, safe to commit).
     The hash is PBKDF2-SHA256 (150,000 rounds), so the public list cannot be reversed into codes.
  3. Rebuilds access-firstuse.js (what login.html reads) and google-apps-script-ams.js
     (what your Google Apps Script checks), from every batch in hashes.json.
  4. Writes the PLAIN codes to a private spreadsheet (XLSX) and CSV. Keep those OUT of git.

Usage
  python3 tools/codes/generate.py --count 200 --batch B1 --out /safe/place/AMS-Sprint-Codes-B1
  (omit --out to write next to this script into tools/codes/private/, which is git-ignored)

Run it again with a new --batch name to add more codes. Old codes keep working.
"""
import argparse, csv, hashlib, json, os, secrets, sys, datetime

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
HASHES = os.path.join(HERE, 'hashes.json')
ALPHABET = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789'   # no I, L, O, 0, 1 (easy to read and type)
SALT = 'ams-fu-v1'
ITER = 150_000


def canon(code):
    return ''.join(c for c in code.upper() if c.isalnum())


def derive(code):
    return hashlib.pbkdf2_hmac('sha256', canon(code).encode(), SALT.encode(), ITER, 32).hex()


def new_code(prefix):
    g = lambda n: ''.join(secrets.choice(ALPHABET) for _ in range(n))
    return f'{prefix}-{g(5)}-{g(5)}'


def load():
    if os.path.exists(HASHES):
        return json.load(open(HASHES))
    return {'salt': SALT, 'iterations': ITER, 'batches': []}


def write_public(db):
    cfg = db['cfg']
    allh = [h for b in db['batches'] for h in b['hashes']]
    js = f"""/* AI Made Simple School: first-use access codes. GENERATED by tools/codes/generate.py. Do not hand-edit.
   Only PBKDF2 hashes are stored here. A code is valid for {cfg['days']} days from the learner's FIRST login. */
window.AMS_FU = {json.dumps({
        'salt': db['salt'], 'iterations': db['iterations'], 'days': cfg['days'],
        'programme': cfg['programme'], 'label': cfg['label'], 'access': cfg['access'],
        'total': len(allh), 'hashes': allh}, indent=1)};
"""
    open(os.path.join(ROOT, 'access-firstuse.js'), 'w').write(js)
    tpl = open(os.path.join(HERE, 'apps-script-template.js')).read()
    open(os.path.join(ROOT, 'google-apps-script-ams.js'), 'w').write(
        tpl.replace('/*__HASHES__*/[]', json.dumps(allh)).replace('__DAYS__', str(cfg['days'])))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--count', type=int, default=200)
    ap.add_argument('--batch', default='B1')
    ap.add_argument('--prefix', default='SPR')
    ap.add_argument('--days', type=int, default=30)
    ap.add_argument('--programme', default='sprint')
    ap.add_argument('--label', default='30-Day AI Sprint')
    ap.add_argument('--out', default=None, help='output path without extension')
    ap.add_argument('--rebuild', action='store_true', help='only rebuild public files from hashes.json')
    a = ap.parse_args()

    db = load()
    db.setdefault('cfg', {'days': a.days, 'programme': a.programme, 'label': a.label,
                          'access': {'sprint': {'days': a.days}} if a.programme == 'sprint' else {}})
    if a.rebuild:
        write_public(db); print('rebuilt public files'); return
    if any(b['id'] == a.batch for b in db['batches']):
        sys.exit(f"Batch {a.batch} already exists. Use a new --batch name (old codes are never regenerated).")

    seen = {h for b in db['batches'] for h in b['hashes']}
    rows = []
    while len(rows) < a.count:
        c = new_code(a.prefix)
        h = derive(c)
        if h in seen: continue
        seen.add(h); rows.append((c, h))
    db['batches'].append({'id': a.batch, 'created': datetime.date.today().isoformat(),
                          'prefix': a.prefix, 'hashes': [h for _, h in rows]})
    json.dump(db, open(HASHES, 'w'), indent=1)
    write_public(db)

    out = a.out or os.path.join(HERE, 'private', f'AMS-{a.programme}-codes-{a.batch}')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    start = sum(len(b['hashes']) for b in db['batches'][:-1])
    with open(out + '.csv', 'w', newline='') as f:
        w = csv.writer(f); w.writerow(['No', 'Code', 'Batch', 'Programme', 'Days'])
        for i, (c, _) in enumerate(rows, 1): w.writerow([start + i, c, a.batch, a.label, a.days])
    make_xlsx(out + '.xlsx', rows, a, start)
    print(f'{len(rows)} codes -> {out}.xlsx / .csv   (public hashes: {sum(len(b["hashes"]) for b in db["batches"])})')


def make_xlsx(path, rows, a, start):
    from openpyxl import Workbook
    from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
    from openpyxl.worksheet.datavalidation import DataValidation
    from openpyxl.formatting.rule import FormulaRule
    wb = Workbook(); ws = wb.active; ws.title = 'Codes'
    gold = PatternFill('solid', fgColor='C9A84C'); dark = Font(bold=True, color='0E0E10')
    head = ['No', 'Access code', 'Sold to (name)', 'WhatsApp / phone', 'Email', 'Amount paid (₦)', 'Date paid',
            'Date code sent', 'First login (auto or type)', 'Expires', 'Status', 'Notes']
    ws.append(head)
    for c in ws[1]:
        c.fill = gold; c.font = dark; c.alignment = Alignment(wrap_text=True, vertical='center')
    n = len(rows)
    for i, (code, _) in enumerate(rows, 1):
        r = i + 1
        ws.append([start + i, code, None, None, None, None, None, None, None,
                   f'=IF(I{r}="","",I{r}+{a.days})',
                   f'=IF(C{r}="","Unsold",IF(I{r}="","Sold, not started",IF(TODAY()>J{r},"Expired","Active")))', None])
    for col, w in zip('ABCDEFGHIJKL', [6, 20, 24, 18, 26, 14, 13, 13, 16, 13, 18, 30]):
        ws.column_dimensions[col].width = w
    for row in ws.iter_rows(min_row=2, max_row=n + 1):
        row[1].font = Font(name='Consolas', bold=True)
        for idx in (6, 7, 8, 9): row[idx].number_format = 'dd-mmm-yyyy'
        row[5].number_format = '#,##0'
    ws.freeze_panes = 'C2'
    ws.auto_filter.ref = f'A1:L{n + 1}'
    rng = f'K2:K{n + 1}'
    for text, color in [('Unsold', 'EDEDED'), ('Sold, not started', 'FFF2CC'), ('Active', 'D9EAD3'), ('Expired', 'F4CCCC')]:
        ws.conditional_formatting.add(rng, FormulaRule(formula=[f'$K2="{text}"'], fill=PatternFill('solid', bgColor=color, fgColor=color)))
    h = wb.create_sheet('How to use')
    for line in [
        f'AI Made Simple School: {a.label} access codes, batch {a.batch} ({n} codes)',
        '',
        'PRIVATE. Do not post, screenshot to groups, or upload to GitHub.',
        '',
        f'• Each code works for {a.days} days, counted from the learner\'s FIRST login (not from the day you sell it).',
        '• One code = one learner. Sell each code once.',
        '1. Learner pays (Paystack or transfer) and sends the receipt on WhatsApp.',
        '2. Pick the next "Unsold" row. Type their name, phone, email, amount and date paid.',
        '3. Send them ONLY the code (and the login link: aimadesimpleschool.com/login.html).',
        '4. When they first log in, the Redemptions tab of your Google Sheet records the start time (if the Apps Script is set up).',
        '   Copy that date into "First login". Expires and Status then fill in by themselves.',
        '5. Refund inside 7 days? Write it in Notes and tell us so the code can be reset.',
        '',
        'Status colours: grey = unsold, yellow = sold but not started, green = active, red = expired.',
    ]: h.append([line])
    h['A1'].font = Font(bold=True, size=14); h.column_dimensions['A'].width = 120
    wb.save(path)


if __name__ == '__main__':
    main()
