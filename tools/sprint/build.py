"""Builds ../../sprint-content.js from gen_sprint.py (+ Anthropic links in ../lessons/gen_src.py).
Run:  python3 tools/sprint/build.py"""
import json, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
ns = {}
exec(open(os.path.join(HERE, '..', 'lessons', 'gen_src.py'), encoding='utf-8').read(), ns)
exec(open(os.path.join(HERE, 'gen_sprint.py'), encoding='utf-8').read(), ns)
SRC = dict(ns['SRC']); SRC.update(ns['SPRINT_SRC'])
DAYS, TRACK_DAYS, TRACKS = ns['DAYS'], ns['TRACK_DAYS'], ns['TRACKS']
# short, practical version + video class for every lesson (tools/sprint/short.py; videos made by marketing/.../source/lessonvid.py)
sh = {}
exec(open(os.path.join(HERE, 'short.py'), encoding='utf-8').read(), sh)
def add_short(L, S, vid):
    L.update(win=S['win'], why=S['why'], do=S['do'], task=S['task'], proof=S['proof'], warn=S['watch'], vid=vid)
for k, L in DAYS.items(): add_short(L, sh['SHORT'][k], f'videos/sprint/d{k:02d}')
for t, days in TRACK_DAYS.items():
    for k, L in days.items(): add_short(L, sh['TRACK_SHORT'][t][k], f'videos/sprint/{t}-d{k:02d}')
core = set(range(1, 31)) - set(range(8, 13))
assert set(DAYS) == core, core ^ set(DAYS)
for t in TRACKS: assert set(TRACK_DAYS[t]) == set(range(8, 13)), t
tokens = set()
for L in list(DAYS.values()) + [l for t in TRACK_DAYS.values() for l in t.values()]:
    for s in L['src']: assert s in SRC, (L['d'], s)
    for f in ('concept', 'prompt', 'apply', 'watch', 't') + tuple(f'steps' for _ in [0]):
        val = ' '.join(L[f]) if isinstance(L[f], list) else L[f]
        tokens |= set(re.findall(r'\{(\w+)\}', val))
for t, v in TRACKS.items(): assert tokens <= set(v), (t, tokens - set(v))
used = {s for L in list(DAYS.values()) + [l for t in TRACK_DAYS.values() for l in t.values()] for s in L['src']}
j = lambda o: json.dumps(o, ensure_ascii=False, indent=1)
out = f"""/* AI Made Simple School: 30-Day Professional AI Sprint content. GENERATED by tools/sprint/build.py. Do not hand-edit.
   {{tokens}} in text are filled from the learner's track at runtime. Explanations written by AI Made Simple,
   drawing on free material published by OpenAI (OpenAI Academy) and Anthropic (Claude Academy, Claude Docs). */
window.AMS_SPRINT={j({'tracks': TRACKS, 'days': {str(k): v for k, v in sorted(DAYS.items())},
  'trackDays': {t: {str(k): v for k, v in d.items()} for t, d in TRACK_DAYS.items()},
  'src': {k: SRC[k] for k in sorted(used)}})};
"""
dst = os.path.normpath(os.path.join(HERE, '..', '..', 'sprint-content.js'))
open(dst, 'w', encoding='utf-8').write(out)
print('wrote', dst, len(out), 'chars; tokens:', sorted(tokens))
